test('October corrections: searches request each changed value without submitting', async ({ page }) => {
  await login(page, 'dev.principal')
  await page.getByRole('button', { name: 'Documentos', exact: true }).click()
  const input = page.getByLabel('Buscar por título')
  for (const value of ['P', 'Pl', 'Pla', 'P', '']) {
    const request = page.waitForRequest(r => new URL(r.url()).pathname === '/api/work-plans' && new URL(r.url()).searchParams.get('query') === value)
    await input.fill(value)
    await request
  }
  await expect(input).toBeFocused()
})

