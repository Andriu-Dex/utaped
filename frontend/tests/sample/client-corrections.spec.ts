test('October corrections: autosave preserves typing during a request and recovers after network failure', async ({ page }) => {
  await login(page, 'dev.principal')
  const options = await api(page, '/work-plans/options')
  const scope = options.scopes.find((s: { canCreate: boolean; groupName: string }) => s.canCreate && s.groupName !== 'Unidad de Titulación')
  const plan = await api(page, '/work-plans', 'POST', { scopeId: scope.id, groupId: scope.groupId, periodId: scope.periodId, requestKey: crypto.randomUUID() })
  await page.goto('/?view=documents&doc=' + plan.id + '&step=content&workspace=documents')
  const objective = page.getByRole('textbox', { name: 'Objetivo', exact: true })
  await expect(objective).toBeVisible()
  await page.route('**/api/work-plans/' + plan.id, async route => {
    if (route.request().method() === 'PUT') await new Promise(resolve => setTimeout(resolve, 500))
    await route.continue()
  })
  const pending = page.waitForRequest(r => r.method() === 'PUT' && new URL(r.url()).pathname === '/api/work-plans/' + plan.id)
  await objective.fill('Objetivo guardado automáticamente')
  await pending
  await objective.fill('Objetivo guardado automáticamente con contenido adicional')
  await expect.poll(async () => (await api(page, '/work-plans/' + plan.id)).objective).toBe('Objetivo guardado automáticamente con contenido adicional')
  await expect(objective).toHaveValue('Objetivo guardado automáticamente con contenido adicional')
  await page.unroute('**/api/work-plans/' + plan.id)
  await page.route('**/api/work-plans/' + plan.id, route => route.request().method() === 'PUT' ? route.fulfill({ status: 503, json: { message: 'Fallo temporal de autoguardado' } }) : route.continue())
  await objective.fill('Cambios conservados durante el fallo')
  await expect(page.getByText('Fallo temporal de autoguardado', { exact: true })).toBeVisible()
  await expect(objective).toHaveValue('Cambios conservados durante el fallo')
  expect((await api(page, '/work-plans/' + plan.id)).objective).toBe('Objetivo guardado automáticamente con contenido adicional')
  await page.unroute('**/api/work-plans/' + plan.id)
  await page.getByRole('button', { name: 'Guardar borrador', exact: true }).click()
  await expect.poll(async () => (await api(page, '/work-plans/' + plan.id)).objective).toBe('Cambios conservados durante el fallo')
  await page.reload()
  await expect(objective).toHaveValue('Cambios conservados durante el fallo')
})

