test('October corrections: proposal consultation distinguishes failure from an empty list and retries', async ({ page }) => {
  await login(page, 'dev.admin')
  let fail = true
  await page.route('**/api/admin/planning/groups/*/activity-proposals', route => route.fulfill(fail ? { status: 503, json: { message: 'Consulta temporalmente no disponible.' } } : { json: [] }))
  await page.getByRole('button', { name: 'Catálogo de actividades', exact: true }).click()
  const groups = await api(page, '/admin/groups')
  await page.getByLabel('Grupo del catálogo').selectOption(groups[0].id)
  const retry = page.getByRole('button', { name: 'Reintentar propuestas', exact: true })
  await expect(retry).toBeVisible()
  await expect(page.getByText('No hay propuestas pendientes de esta unidad o comisión.', { exact: true })).toHaveCount(0)
  fail = false
  await retry.click()
  await expect(page.getByText('No hay propuestas pendientes de esta unidad o comisión.', { exact: true })).toBeVisible()
  await expect(retry).toHaveCount(0)
})
