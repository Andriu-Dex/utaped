import { test, expect } from '@playwright/test'
import { randomUUID } from 'node:crypto'
import { api, login } from './sample-fixtures'

test('live A4 preview follows unsaved content without saving or creating an artifact, with tablet modes and retries', async ({ page }) => {
  await page.setViewportSize({ width: 1600, height: 1100 })
  await login(page, 'dev.principal')
  const options = await api(page, '/work-plans/options')
  const scope = options.scopes.find((s: { canCreate: boolean; groupName: string }) => s.canCreate && s.groupName !== 'Unidad de Titulación')
  expect(scope).toBeTruthy()
  const plan = await api(page, '/work-plans', 'POST', { groupId: scope.groupId, periodId: scope.periodId, scopeId: scope.id, requestKey: randomUUID(), title: 'Vista simultánea de aceptación' })
  await page.goto('/?view=documents&doc=' + plan.id + '&step=content')
  const justification = page.getByLabel('Justificación', { exact: true })
  const objective = page.getByLabel('Objetivo', { exact: true })
  await expect(justification).toBeVisible()
  await justification.fill('Contenido local para comprobar el documento A4 sin guardar. '.repeat(90))
  await objective.fill('Objetivo escrito mientras se revisa el documento.')
  const preview = page.getByRole('complementary', { name: 'Previsualización simultánea del Plan' })
  await expect(preview.getByRole('img', { name: /del borrador A4/ })).toBeVisible({ timeout: 90000 })
  await expect(preview.getByRole('status').filter({ hasText: 'Vista actualizada · cambios sin guardar' })).toBeVisible()
  expect((await api(page, '/work-plans/' + plan.id)).justification).not.toContain('Contenido local')
  expect((await api(page, '/work-plans/' + plan.id)).justification).toContain('Plan de Trabajo')
  expect(await api(page, '/work-plans/' + plan.id + '/artifacts')).toHaveLength(0)
  await expect(preview.getByRole('button', { name: 'Página anterior' })).toBeEnabled()
  await preview.getByRole('spinbutton', { name: 'Ir a página', exact: true }).fill('0')
  await preview.getByRole('spinbutton', { name: 'Ir a página', exact: true }).press('Tab')
  await expect(preview.getByRole('spinbutton', { name: 'Ir a página', exact: true })).toHaveValue('0')
  await expect(preview.getByRole('spinbutton', { name: 'Ir a página', exact: true })).toHaveAttribute('aria-invalid', 'true')
  await expect(preview.getByText(/Introduce una página entre 1 y/)).toBeVisible()
  await preview.getByRole('spinbutton', { name: 'Ir a página', exact: true }).fill('1')
  await preview.getByRole('spinbutton', { name: 'Ir a página', exact: true }).press('Enter')
  await expect(preview.getByRole('status').filter({ hasText: /Pág\. 1 de/ })).toBeVisible()
  await preview.getByRole('button', { name: /^Objetivo/ }).click()
  await expect(preview.getByRole('button', { name: 'Página anterior' })).toBeEnabled()

  const editor = page.locator('.live-preview-editor')
  const editorBox = await editor.boundingBox(), previewBox = await preview.boundingBox()
  expect(editorBox!.x + editorBox!.width).toBeLessThan(previewBox!.x)
  await page.getByLabel('Ancho del formulario').focus(); await page.getByLabel('Ancho del formulario').press('ArrowRight'); await expect(page.getByLabel('Ancho del formulario')).toHaveValue('47')
  await page.screenshot({ path: 'test-results/live-preview-desktop.png', fullPage: true })
  await preview.getByRole('button', { name: 'Ampliar página', exact: true }).click()
  await expect(page.getByRole('dialog', { name: /Borrador A4/ })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 820, height: 1180 })
  await expect(justification).toBeVisible()
  await expect(preview).not.toBeVisible()
  await page.getByRole('button', { name: 'Previsualizar documento', exact: true }).click()
  await expect(preview).toBeVisible()
  await expect(justification).not.toBeVisible()
  await page.getByRole('button', { name: 'Modo oscuro', exact: true }).click()
  await page.screenshot({ path: 'test-results/live-preview-tablet-dark.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.route('**/artifacts/draft-preview', route => route.fulfill({ status: 503, json: { message: 'Vista temporalmente ocupada.' } }))
  await preview.getByRole('button', { name: 'Actualizar vista', exact: true }).click()
  await expect(page.getByText('Vista temporalmente ocupada.', { exact: true })).toBeVisible()
  await page.unroute('**/artifacts/draft-preview')
  await preview.getByRole('button', { name: 'Actualizar vista', exact: true }).click()
  await expect(preview.getByRole('status').filter({ hasText: 'Vista actualizada · cambios sin guardar' })).toBeVisible({ timeout: 90000 })
  await page.getByRole('button', { name: 'Editar contenido', exact: true }).click()
  await expect(objective).toHaveValue('Objetivo escrito mientras se revisa el documento.')
  await page.getByRole('button', { name: 'Guardar borrador', exact: true }).click()
  await expect(page.getByText('Borrador guardado en el servidor.', { exact: true })).toBeVisible()
  expect((await api(page, '/work-plans/' + plan.id)).objective).toBe('Objetivo escrito mientras se revisa el documento.')
})
