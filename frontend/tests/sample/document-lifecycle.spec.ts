import { test, expect } from '@playwright/test'
import { randomUUID } from 'node:crypto'
import { api, login, acceptanceBaseURL } from './sample-fixtures'
import { withConfirmation } from '../confirmation'

const date = (days: number) => new Date(Date.now() + days * 86400000).toISOString().slice(0, 10)
test('draft discard is scoped, confirmed, permission-aware and preserves errors and focus', async ({ page, browser }) => {
  const contexts = await Promise.all([browser.newContext({ baseURL: acceptanceBaseURL }), browser.newContext({ baseURL: acceptanceBaseURL })])
  try {
    const author = await login(page, 'dev.principal'), admin = await contexts[0].newPage(), member = await contexts[1].newPage()
    await login(admin, 'dev.admin'); const reader = await login(member, 'dev.member')
    const suffix = randomUUID().slice(0, 8)
    const group = await api(admin, '/admin/groups', 'POST', { name: 'Comisión descarte ' + suffix, groupType: 'COMMISSION' })
    const period = await api(admin, '/admin/periods', 'POST', { name: 'Período descarte ' + suffix, startsOn: date(-2), endsOn: date(60), preparationStartsOn: date(-2), reviewStartsOn: date(-2), reviewEndsOn: date(60) })
    const scope = await api(admin, '/admin/organization/scopes', 'POST', { groupId: group.id, periodId: period.id, careerId: null })
    for (const person of [author, reader]) await api(admin, '/admin/organization/scopes/' + scope.id + '/members', 'PUT', { userId: person.id, membershipRole: 'MEMBER', positionLabel: 'Docente', active: true, rowVersion: 0 })
    await api(admin, '/admin/organization/scopes/' + scope.id + '/principal', 'PUT', { userId: author.id, rowVersion: 0 })
    const plan = await api(page, '/work-plans', 'POST', { scopeId: scope.id, groupId: group.id, periodId: period.id, title: 'Borrador para descartar ' + suffix, requestKey: randomUUID() })
    const sentinel = (await api(page, '/work-plans?size=50')).items.find((item: { id: string }) => item.id !== plan.id)
    await member.getByRole('button', { name: 'Documentos', exact: true }).click()
    await member.getByPlaceholder('Escriba palabras del título…').fill(suffix); await member.getByRole('button', { name: 'Buscar', exact: true }).click()
    await expect(member.getByRole('button', { name: 'Ver ' + plan.title, exact: false })).toBeVisible()
    await expect(member.getByRole('button', { name: 'Descartar borrador: ' + plan.title, exact: true })).toHaveCount(0)
    const csrf = await api(member, '/auth/csrf')
    expect((await member.request.post('/api/work-plans/' + plan.id + '/archive', { headers: { [csrf.headerName]: csrf.token }, data: { rowVersion: plan.rowVersion, reason: 'No autorizado' } })).status()).toBe(403)
    await page.getByRole('button', { name: 'Documentos', exact: true }).click()
    await page.getByPlaceholder('Escriba palabras del título…').fill(suffix); await page.getByRole('button', { name: 'Buscar', exact: true }).click()
    const trigger = page.getByRole('button', { name: 'Descartar borrador: ' + plan.title, exact: true })
    await trigger.click()
    const dialog = page.getByRole('dialog', { name: 'Descartar borrador', exact: true })
    await expect(dialog.getByRole('button', { name: 'Cancelar', exact: true })).toBeFocused()
    await expect(dialog.getByRole('button', { name: 'Descartar borrador', exact: true })).toBeDisabled()
    await dialog.getByLabel('Motivo del descarte').fill('   ')
    await expect(dialog.getByRole('button', { name: 'Descartar borrador', exact: true })).toBeDisabled()
    await dialog.getByLabel('Motivo del descarte').fill('Borrador de validación descartado.')
    await withConfirmation(page, false, () => dialog.press('Escape'))
    await expect(dialog.getByLabel('Motivo del descarte')).toHaveValue('Borrador de validación descartado.')
    await withConfirmation(page, true, () => dialog.getByRole('button', { name: 'Cancelar', exact: true }).click())
    await expect(trigger).toBeFocused(); expect((await api(page, '/work-plans/' + plan.id)).archivedAt).toBeNull()
    await trigger.click(); await dialog.getByLabel('Motivo del descarte').fill('Borrador de validación descartado.')
    await page.route('**/api/work-plans/' + plan.id + '/archive', route => route.fulfill({ status: 409, json: { message: 'El documento cambió. Recargue antes de continuar.' } }))
    await dialog.getByRole('button', { name: 'Descartar borrador', exact: true }).click()
    await expect(page.getByText('El documento cambió. Recargue antes de continuar.', { exact: true })).toBeVisible()
    await expect(dialog.getByLabel('Motivo del descarte')).toHaveValue('Borrador de validación descartado.')
    await page.unroute('**/api/work-plans/' + plan.id + '/archive')
    await page.setViewportSize({ width: 820, height: 1180 }); await page.getByRole('button', { name: 'Modo oscuro', exact: true }).click()
    await dialog.screenshot({ path: 'test-results/discard-document-tablet-dark.png' })
    await dialog.getByRole('button', { name: 'Descartar borrador', exact: true }).click()
    await expect(dialog).not.toBeVisible(); await expect(page.getByText('Borrador descartado.', { exact: true })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Mis documentos', exact: true })).toBeFocused()
    await expect(trigger).toHaveCount(0)
    expect((await page.request.get('/api/work-plans/' + plan.id)).status()).toBe(404)
    expect((await api(admin, '/work-plans/' + plan.id)).archivedAt).toBeTruthy()
    if (sentinel) expect((await api(page, '/work-plans/' + sentinel.id)).archivedAt).toBe(sentinel.archivedAt)
  } finally { for (const context of contexts) await context.close() }
})
