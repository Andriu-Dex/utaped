import { test, expect } from '@playwright/test'
import { randomUUID } from 'node:crypto'
import { api, login } from './sample-fixtures'
import { openPlanFollowUp } from '../plan-navigation'

test('Plan follow-up is separate, keyboard accessible and returns to its source step', async ({ page }) => {
  await login(page, 'dev.principal')
  const options = await api(page, '/work-plans/options')
  const scope = options.scopes.find((item: { canCreate: boolean }) => item.canCreate)
  expect(scope).toBeTruthy()
  const title = 'Seguimiento ' + randomUUID()
  await api(page, '/work-plans', 'POST', { scopeId: scope.id, groupId: scope.groupId, periodId: scope.periodId, title, requestKey: randomUUID() })
  await page.getByRole('button', { name: 'Documentos', exact: true }).click()
  await page.getByLabel('Buscar por título').fill(title)
  await page.getByRole('button', { name: 'Buscar', exact: true }).click()
  await page.getByRole('button', { name: 'Editar ' + title, exact: false }).click()
  const trigger = page.getByRole('button', { name: 'Seguimiento del documento', exact: true })
  const panel = page.getByRole('region', { name: 'Opciones de seguimiento' })
  await expect(panel).toHaveCount(0)
  await expect(page.locator('.plan-editor-pane').getByRole('button', { name: 'Seguimiento del documento' })).toHaveCount(0)
  await trigger.focus(); await trigger.press('ArrowDown')
  await expect(panel.getByRole('button', { name: 'Rondas y observaciones', exact: true })).toBeFocused()
  await expect(panel.getByRole('button', { name: 'Ejecución y evidencias', exact: true })).toHaveCount(0)
  await page.screenshot({ path: 'test-results/plan-follow-up-desktop.png', fullPage: true })
  await page.keyboard.press('Escape'); await expect(trigger).toBeFocused(); await expect(panel).toHaveCount(0)
  await trigger.click(); await page.getByRole('heading', { name: title, exact: true }).click(); await expect(panel).toHaveCount(0)
  const steps = page.getByRole('navigation', { name: 'Pasos del Plan', exact: true })
  await steps.getByRole('button').nth(1).click()
  await page.getByRole('textbox', { name: 'Objetivo', exact: true }).fill('Objetivo sin guardar')
  await trigger.click()
  await expect(panel.getByRole('button', { name: 'Historial del documento', exact: true })).toBeDisabled()
  await expect(panel.getByText('Guarde los cambios pendientes antes de abrir el seguimiento.')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Guardar borrador', exact: true }).click()
  await openPlanFollowUp(page, 'Historial del documento')
  await page.getByRole('button', { name: 'Volver al documento', exact: true }).click()
  await expect(steps.getByRole('button').nth(1)).toHaveAttribute('aria-current', 'step')
  await expect(page.getByRole('textbox', { name: 'Objetivo', exact: true })).toHaveValue('Objetivo sin guardar')
  await openPlanFollowUp(page, 'Rondas y observaciones')
  await page.getByRole('button', { name: 'Volver al documento', exact: true }).click()
  await expect(steps.getByRole('button').nth(1)).toHaveAttribute('aria-current', 'step')
  await page.setViewportSize({ width: 820, height: 1180 })
  await page.getByRole('button', { name: 'Modo oscuro', exact: true }).click()
  await trigger.click()
  await page.screenshot({ path: 'test-results/plan-follow-up-tablet-dark.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
})
