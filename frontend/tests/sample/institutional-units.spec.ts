import { randomUUID } from 'node:crypto'
import { test, expect } from '@playwright/test'
import { api, login } from './sample-fixtures'
import { openAction } from '../open-action'

test('admin configures administrative provenance and the Plan inherits locked catalogue values', async ({ page }) => {
  await login(page, 'dev.admin')
  const suffix = randomUUID().slice(0, 8), name = 'Unidad administrativa de aceptación ' + suffix
  await page.getByRole('button', { name: 'Carreras y ámbitos', exact: true }).click()
  await page.getByRole('button', { name: 'Crear unidad', exact: true }).click()
  await page.getByLabel('Tipo de unidad', { exact: true }).selectOption('ADMINISTRATIVE')
  await page.getByLabel('Nombre de la unidad', { exact: true }).fill(name)
  await page.getByRole('button', { name: 'Guardar unidad', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: name })).toContainText('Administrativa')
  const units = await api(page, '/institutional-units'), unit = units.find((u: { name: string }) => u.name === name)
  const group = await api(page, '/admin/groups', 'POST', { name: 'Grupo procedencia ' + suffix, groupType: 'UNIT' })
  const start = new Date(Date.now() - 86400000).toISOString().slice(0, 10), end = new Date(Date.now() + 30 * 86400000).toISOString().slice(0, 10)
  const period = await api(page, '/admin/periods', 'POST', { name: 'Período procedencia ' + suffix, startsOn: start, endsOn: end, preparationStartsOn: start, preparationEndsOn: end, reviewStartsOn: start, reviewEndsOn: end })
  await page.reload()
  await openAction(page, 'Crear ámbito')
  await page.getByLabel('Tipo de unidad del ámbito', { exact: true }).selectOption('ADMINISTRATIVE')
  await page.getByLabel('Unidad del ámbito', { exact: true }).selectOption(unit.id)
  await expect(page.getByLabel('Carrera del ámbito', { exact: true })).toBeDisabled()
  await page.getByLabel('Grupo del ámbito', { exact: true }).selectOption(group.id)
  await page.getByLabel('Período del ámbito', { exact: true }).selectOption(period.id)
  await page.getByRole('region', { name: 'Formulario: Crear ámbito', exact: true }).getByRole('button', { name: 'Crear ámbito', exact: true }).click()
  await expect(page.getByText('Configuración guardada.', { exact: true })).toBeVisible()
  const scopes = await api(page, '/organization/scopes'), scope = scopes.find((s: { group_id: string }) => s.group_id === group.id)
  expect(scope.institutional_unit_id).toBe(unit.id)
  const directory = await api(page, '/admin/users/directory?query=Andr%C3%A9s&active=true&size=100'), principal = directory.items.find((u: { username: string }) => u.username === 'dev.principal')
  await api(page, '/admin/organization/scopes/' + scope.id + '/members', 'PUT', { userId: principal.id, membershipRole: 'MEMBER', positionLabel: 'Responsable de ejemplo', active: true, rowVersion: 0 })
  await api(page, '/admin/organization/scopes/' + scope.id + '/principal', 'PUT', { userId: principal.id, rowVersion: 0 })
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
  await login(page, 'dev.principal')
  const plan = await api(page, '/work-plans', 'POST', { scopeId: scope.id, groupId: group.id, periodId: period.id, requestKey: randomUUID(), title: 'Plan administrativo ' + suffix })
  expect(plan.institutionalUnitType).toBe('ADMINISTRATIVE'); expect(plan.institutionalUnit).toBe(name); expect(plan.career).toBe('')
  await page.getByRole('button', { name: 'Documentos', exact: true }).click()
  await page.getByLabel('Buscar por título').fill(plan.title)
  await page.getByRole('button', { name: 'Buscar', exact: true }).click()
  await page.getByRole('button', { name: 'Editar ' + plan.title, exact: false }).click()
  await expect(page.getByLabel('Tipo de unidad', { exact: true })).toHaveValue('ADMINISTRATIVE')
  await expect(page.getByLabel('Unidad institucional', { exact: true })).toBeDisabled()
  await expect(page.getByLabel('Unidad institucional', { exact: true })).toHaveValue(name)
  await expect(page.getByLabel('Carrera, cuando corresponda', { exact: true })).toHaveCount(0)
  await page.getByRole('region', { name: 'Procedencia institucional', exact: true }).screenshot({ path: 'test-results/institutional-provenance.png' })
})
