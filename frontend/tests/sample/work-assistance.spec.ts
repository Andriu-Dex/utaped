import { test, expect } from '@playwright/test'
import { api, login } from './sample-fixtures'

test('personal pending inbox supports filtering, recovery, direct navigation and tablet dark mode', async ({ page }) => {
  await login(page, 'dev.principal')
  const live = await api(page, '/pending-work')
  expect(live.counts).toHaveProperty('EVIDENCE')
  const plans = await api(page, '/work-plans?size=20')
  const plan = plans.items.find((item: { documentType: string; editable: boolean }) => item.documentType === 'T1' && item.editable)
  expect(plan).toBeTruthy()
  let unavailable = false
  const queries: string[] = []
  await page.route('**/api/pending-work?**', route => {
    const params = new URL(route.request().url()).searchParams; queries.push(params.toString())
    const items = [{ id: 'correction', kind: 'CORRECTION', documentId: plan.id, title: plan.title, detail: 'Revisar observaciones de la segunda ronda', groupName: plan.groupName, periodName: plan.periodName, deadline: null, overdue: false, step: 'general', action: 'Corregir documento' }, { id: 'evidence', kind: 'EVIDENCE', documentId: plan.id, title: plan.title, detail: 'Consolidar evidencias académicas · 2 medios pendientes', groupName: plan.groupName, periodName: plan.periodName, deadline: '2026-10-20', overdue: true, step: 'execution', action: 'Consultar plazo' }].filter(item => !params.get('kind') || params.get('kind') === item.kind)
    return unavailable ? route.fulfill({ status: 503, json: { message: 'Pendientes temporalmente no disponibles.' } }) : route.fulfill({ json: { items, total: items.length, page: 0, size: 5, counts: { CORRECTION: 1, REVIEW: 0, SIGNATURE: 0, EVIDENCE: 1 } } })
  })
  const inbox = page.getByRole('region', { name: 'Mis pendientes', exact: true })
  await inbox.getByRole('button', { name: 'Actualizar mis pendientes', exact: true }).click()
  await expect(inbox.getByRole('button', { name: /^Corregir documento:/ })).toBeVisible()
  await inbox.getByRole('button', { name: /^Todos/ }).click()
  await expect(inbox.getByRole('button', { name: /^Corregir documento:/ })).toBeVisible()
  await inbox.screenshot({ path: 'test-results/pending-inbox-desktop.png' })
  await inbox.getByRole('button', { name: /^Evidencias/ }).click()
  await expect.poll(() => queries.at(-1)).toContain('kind=EVIDENCE')
  await expect(inbox.getByText('Plazo vencido', { exact: false })).toBeVisible()
  await expect(inbox.getByRole('button', { name: /^Corregir documento:/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Modo oscuro', exact: true }).click()
  await page.setViewportSize({ width: 820, height: 1180 })
  await inbox.screenshot({ path: 'test-results/pending-inbox-tablet-dark.png' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  unavailable = true
  await inbox.getByRole('button', { name: 'Actualizar mis pendientes', exact: true }).click()
  await expect(inbox.getByRole('button', { name: 'Reintentar pendientes' })).toBeVisible()
  unavailable = false
  await inbox.getByRole('button', { name: 'Reintentar pendientes' }).click()
  await inbox.getByRole('button', { name: /^Todos/ }).click()
  await inbox.getByRole('button', { name: /^Corregir documento:/ }).click()
  await expect(page.getByRole('navigation', { name: 'Pasos del Plan', exact: true })).toBeVisible()
  await expect(page).toHaveURL(new RegExp('doc=' + plan.id))
})

test('signing checklist guides to the missing section without changing the document', async ({ page }) => {
  await login(page, 'dev.principal')
  const plans = await api(page, '/work-plans?size=20')
  const item = plans.items.find((plan: { documentType: string; editable: boolean }) => plan.documentType === 'T1' && plan.editable)
  expect(item).toBeTruthy()
  const initial = await api(page, '/work-plans/' + item.id)
  const before = await api(page, '/work-plans/' + item.id, 'PUT', { rowVersion: initial.rowVersion, title: initial.title, institutionalUnit: initial.institutionalUnit, career: initial.career, justification: initial.justification, objective: '' })
  await page.goto('/?view=documents&doc=' + item.id + '&step=signing&workspace=documents')
  const checklist = page.getByRole('region', { name: 'Comprobación antes de firmar', exact: true })
  await expect(checklist).toBeVisible()
  await expect(checklist.getByText('Complete el objetivo.', { exact: true })).toBeVisible()
  await checklist.screenshot({ path: 'test-results/signature-checklist-desktop.png' })
  await checklist.getByRole('button', { name: 'Revisar contenido', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Objetivo', exact: true })).toBeVisible()
  const after = await api(page, '/work-plans/' + item.id)
  expect(after.rowVersion).toBe(before.rowVersion)
})

test('review comparison is explicit, recoverable and compares conserved rounds without another viewer', async ({ page }) => {
  await login(page, 'dev.reviewer')
  const tasks = await api(page, '/reviews/tasks')
  const task = tasks.find((item: { status: string }) => item.status === 'ACTIVE')
  test.skip(!task, 'Needs prepared documents: scripts/test-acceptance.ps1 -PreparedDocuments')
  const live = await api(page, '/reviews/' + task.reviewId + '/comparison')
  expect(live.currentRound).toBe(1)
  expect(live.previousRound).toBeNull()
  let unavailable = true
  await page.route('**/api/reviews/' + task.reviewId + '/comparison', route => unavailable ? route.fulfill({ status: 503, json: { message: 'Comparación temporalmente no disponible.' } }) : route.fulfill({ json: { currentRound: 2, previousRound: 1, changes: [{ section: 'Justificación', before: 'Texto presentado en la primera ronda.', after: 'Texto corregido según la observación del revisor.' }] } }))
  await page.goto('/?view=documents&doc=' + task.documentId + '&step=signing&workspace=documents')
  const comparison = page.getByRole('region', { name: 'Comparación entre rondas', exact: true })
  await expect(comparison.getByRole('button', { name: 'Comparar rondas' })).toBeVisible()
  await comparison.getByRole('button', { name: 'Comparar rondas' }).click()
  await expect(comparison.getByRole('alert')).toBeVisible()
  unavailable = false
  await comparison.getByRole('button', { name: 'Reintentar comparación' }).click()
  const section = comparison.locator('summary')
  await section.focus(); await section.press('Enter')
  await expect(comparison.getByText('Texto presentado en la primera ronda.', { exact: true })).toBeVisible()
  await expect(comparison.getByText('Texto corregido según la observación del revisor.', { exact: true })).toBeVisible()
  await comparison.screenshot({ path: 'test-results/round-comparison-desktop.png' })
  await page.getByRole('button', { name: 'Modo oscuro', exact: true }).click()
  await page.setViewportSize({ width: 820, height: 1180 })
  await comparison.screenshot({ path: 'test-results/round-comparison-tablet-dark.png' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await comparison.getByRole('button', { name: 'Cerrar comparación' }).click()
  await expect(comparison.getByText('Texto presentado en la primera ronda.', { exact: true })).toHaveCount(0)
})

test('report checklists guide T2 and T3 to their own narrative steps without editing the base Plan', async ({ page }) => {
  await login(page, 'dev.principal')
  const plans = await api(page, '/work-plans?size=20')
  const report = plans.items.find((item: { documentType: string; editable: boolean }) => item.documentType === 'T2' && item.editable)
  test.skip(!report, 'Needs prepared documents: scripts/test-acceptance.ps1 -PreparedDocuments')
  const state = await api(page, '/reports/' + report.id)
  const base = await api(page, '/work-plans/' + state.data.basePlanId)
  await api(page, '/reports/' + report.id, 'PUT', { ...state.data, title: state.document.title, rowVersion: state.document.rowVersion, conclusions: '' })
  await page.goto('/?view=documents&doc=' + report.id + '&step=preparation&workspace=documents')
  const checklist = page.getByRole('region', { name: 'Comprobación antes de firmar', exact: true })
  await expect(checklist.getByText('Complete las conclusiones del Informe.', { exact: true })).toBeVisible()
  await checklist.getByRole('button', { name: 'Revisar conclusiones', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Conclusiones', exact: true })).toBeVisible()
  expect((await api(page, '/work-plans/' + base.id)).rowVersion).toBe(base.rowVersion)
  const execution = await api(page, '/work-plans/' + base.id + '/execution-report', 'POST')
  await page.goto('/?view=documents&doc=' + execution.id + '&step=6&workspace=documents')
  await expect(checklist.getByText('Complete el análisis de los resultados de la comisión.', { exact: true })).toBeVisible()
  await checklist.getByRole('button', { name: 'Revisar análisis de resultados', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Análisis de resultados', exact: true })).toBeVisible()
  expect((await api(page, '/work-plans/' + base.id)).rowVersion).toBe(base.rowVersion)
})
