  await page.getByRole('button', { name: 'Ver detalle de la actividad 1', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Cerrar modal', exact: true })).toBeEnabled()
  await expect(page.getByLabel('Desde', { exact: true })).toBeDisabled()
  await page.keyboard.press('Tab')
