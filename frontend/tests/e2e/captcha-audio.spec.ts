import { test, expect } from '@playwright/test'

test('audio challenge supports keyboard, repeat, renewal and preserves credentials', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  const pending = page.waitForResponse(r => new URL(r.url()).pathname === '/api/auth/captcha')
  await page.goto('/')
  const challenge = await pending
  await expect(page.getByRole('button', { name: 'Ingresar', exact: true })).toBeEnabled()
  await page.getByLabel('Usuario', { exact: true }).fill('usuario.sin.enviar')
  await page.getByLabel('Contraseña', { exact: true }).fill('Password-not-submitted')
  const listen = page.getByRole('button', { name: 'Escuchar código', exact: true })
  await listen.focus(); await page.keyboard.press('Enter')
  await expect(listen).toHaveAttribute('aria-expanded', 'true')
  const audio = page.locator('audio')
  await expect(audio).toBeFocused()
  await expect(audio).toHaveAttribute('src', '/api/auth/captcha/audio?id=' + challenge.headers()['x-captcha-id'])
  const playing = page.waitForResponse(r => new URL(r.url()).pathname === '/api/auth/captcha/audio')
  await audio.evaluate(async (element: HTMLAudioElement) => { await element.play() })
  const response = await playing; expect(response.status()).toBe(200)
  expect(response.headers()['cache-control']).toContain('no-store')
  const bytes = await response.body(); expect(bytes.subarray(0, 4).toString()).toBe('RIFF')
  await expect.poll(() => audio.evaluate((element: HTMLAudioElement) => element.currentTime)).toBeGreaterThan(0)
  await audio.evaluate((element: HTMLAudioElement) => { element.pause(); element.currentTime = 0 })
  await audio.evaluate(async (element: HTMLAudioElement) => { await element.play() })
  await audio.evaluate((element: HTMLAudioElement) => element.pause())
  await page.screenshot({ path: 'test-results/captcha-audio-desktop.png', fullPage: true, animations: 'disabled' })
  const old = await audio.getAttribute('src')
  const renewed = page.waitForResponse(r => new URL(r.url()).pathname === '/api/auth/captcha')
  await page.getByRole('button', { name: 'Cambiar código de verificación', exact: true }).click(); await renewed
  await expect(audio).toHaveCount(0)
  await expect(page.getByLabel('Usuario', { exact: true })).toHaveValue('usuario.sin.enviar')
  await expect(page.getByLabel('Contraseña', { exact: true })).toHaveValue('Password-not-submitted')
  expect((await page.request.get(old!)).status()).toBe(404)
  await page.setViewportSize({ width: 820, height: 1180 })
  await page.getByRole('button', { name: 'Modo oscuro', exact: true }).click()
  await listen.click(); await expect(audio).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/captcha-audio-tablet-dark.png', fullPage: true, animations: 'disabled' })
})

test('audio failure is actionable and delayed obsolete challenges are discarded', async ({ page }) => {
  await page.route('**/api/auth/captcha/audio?*', route => route.fulfill({ status: 404, contentType: 'application/json', body: '{}' }))
  await page.goto('/')
  await page.getByRole('button', { name: 'Escuchar código', exact: true }).click()
  await page.locator('audio').evaluate((element: HTMLAudioElement) => element.load())
  await expect(page.getByRole('alert')).toContainText('No se pudo reproducir el audio')
  await expect(page.getByRole('button', { name: 'Cambiar código de verificación', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Cerrar aviso' }).click()
  let release!: () => void
  const blocked = new Promise<void>(resolve => { release = resolve })
  let intercepted!: () => void
  const started = new Promise<void>(resolve => { intercepted = resolve })
  await page.route('**/api/auth/captcha?v=*', async route => { intercepted(); await blocked; await route.fulfill({ status: 200, headers: { 'X-Captcha-Id': '00000000-0000-0000-0000-000000000000' }, contentType: 'image/png', body: Buffer.from('invalid image') }) })
  await page.getByRole('button', { name: 'Cambiar código de verificación', exact: true }).click(); await started
  await page.getByRole('button', { name: '¿Olvidó su contraseña?' }).click(); release()
  await expect(page.getByRole('heading', { name: 'Recuperar acceso' })).toBeVisible()
  await expect(page.locator('audio')).toHaveCount(0)
  await page.unroute('**/api/auth/captcha?v=*')
  await page.getByRole('button', { name: 'Volver al inicio de sesión' }).click()
  await expect(page.getByRole('button', { name: 'Escuchar código', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Escuchar código', exact: true }).click()
  await expect(page.locator('audio')).not.toHaveAttribute('src', /00000000/)
})
