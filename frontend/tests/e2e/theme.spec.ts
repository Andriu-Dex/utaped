import { test, expect } from '@playwright/test'

test('theme follows the system until chosen, persists and synchronizes tabs', async ({ page, context }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.emulateMedia({ colorScheme: 'light' })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Iniciar sesión' })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  const dark = page.getByRole('button', { name: 'Modo oscuro', exact: true })
  await expect(page.getByRole('tooltip')).toBeHidden()
  await dark.focus()
  await expect(page.getByRole('tooltip')).toHaveText('Modo oscuro')
  await page.keyboard.press('Enter')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(page.getByRole('button', { name: 'Modo claro', exact: true })).toBeVisible()
  await expect(page.locator('.access-form-pane')).toHaveCSS('background-color', 'rgb(14, 29, 44)')
  await expect(page.getByLabel('Usuario', { exact: true })).toHaveCSS('background-color', 'rgb(16, 34, 52)')
  await expect(page.locator('.captcha-image')).toHaveCSS('filter', 'none')
  await page.getByLabel('Usuario', { exact: true }).fill('usuario.sin.enviar')
  await page.getByRole('button', { name: 'Modo claro', exact: true }).click()
  await expect(page.getByLabel('Usuario', { exact: true })).toHaveValue('usuario.sin.enviar')
  await page.getByRole('button', { name: 'Modo oscuro', exact: true }).click()
  await page.mouse.move(100, 100)
  await page.getByLabel('Contraseña', { exact: true }).fill('Theme-only-invalid-password')
  await page.getByLabel('Código de verificación', { exact: true }).fill('000000')
  await expect(page.getByRole('button', { name: 'Ingresar', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Ingresar', exact: true }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.locator('.toast')).toHaveCSS('background-color', 'rgb(27, 48, 68)')
  await page.screenshot({ path: 'test-results/theme-access-dark-desktop.png', fullPage: true, animations: 'disabled' })
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  const other = await context.newPage()
  await other.emulateMedia({ colorScheme: 'light' })
  await other.goto('/')
  await expect(other.getByRole('button', { name: 'Modo claro', exact: true })).toBeVisible()
  await other.getByRole('button', { name: 'Modo claro', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await other.evaluate(() => localStorage.removeItem('utaped-theme'))
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.emulateMedia({ media: 'print' })
  await expect(page.getByRole('button', { name: 'Modo claro', exact: true })).toBeHidden()
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(255, 255, 255)')
})

test('tablet theme switching works when browser storage is unavailable', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 820, height: 1180 })
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.addInitScript(() => {
    Storage.prototype.getItem = () => { throw new DOMException('Storage blocked', 'SecurityError') }
    Storage.prototype.setItem = () => { throw new DOMException('Storage blocked', 'SecurityError') }
  })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Iniciar sesión' })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: 'test-results/theme-access-dark-tablet.png', fullPage: true, animations: 'disabled' })
  const light = page.getByRole('button', { name: 'Modo claro', exact: true })
  await light.hover()
  await expect(page.getByRole('tooltip')).toBeVisible()
  await light.click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  expect(errors).toEqual([])
})
